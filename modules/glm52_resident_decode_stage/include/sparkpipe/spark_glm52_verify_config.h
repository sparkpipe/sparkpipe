#pragma once

#include <stdint.h>
#include <stdlib.h>

#include "sparkpipe/spark_speculation_verify_plan.h"

#define SPARK_GLM52_VERIFY_ROWS_ENV "SPARK_GLM52_VERIFY_ROWS"
#define SPARK_GLM52_VERIFY_DRAFTER_ENV "SPARK_GLM52_VERIFY_DRAFTER"
#define SPARK_GLM52_TAP_DUMP_ENV "SPARK_GLM52_TAP_DUMP"
#define SPARK_GLM52_TAP_RECORD_MAGIC 0x31505447u
#define SPARK_GLM52_RELAY_COMMIT_MAGIC 0x31435347u
#define SPARK_GLM52_RELAY_DRAFT_MAGIC 0x31445347u
#define SPARK_GLM52_RELAY_ANSWER_MAGIC 0x31415347u
#define SPARK_GLM52_RELAY_TIMEOUT_SECONDS 20
