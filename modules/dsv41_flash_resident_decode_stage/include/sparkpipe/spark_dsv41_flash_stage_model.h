#ifndef SPARK_DSV41_FLASH_STAGE_TP_DEGREE
#define SPARK_DSV41_FLASH_STAGE_TP_DEGREE 16u
#endif
#define SPARK_DSV41_FLASH_STAGE_PP_STAGES (16u / SPARK_DSV41_FLASH_STAGE_TP_DEGREE)
#define SPARK_DSV41_FLASH_STAGE_FULL_ROW_LAYERS 20u
#define SPARK_DSV41_FLASH_STAGE_FIRST_LAYER(stage) ((stage) * (SPARK_DSV41_FLASH_STAGE_FULL_ROW_LAYERS / SPARK_DSV41_FLASH_STAGE_PP_STAGES))
#define SPARK_DSV41_FLASH_STAGE_LAYER_COUNT(stage) ((stage) + 1u == SPARK_DSV41_FLASH_STAGE_PP_STAGES ? \
	40u - SPARK_DSV41_FLASH_STAGE_FIRST_LAYER(stage) : SPARK_DSV41_FLASH_STAGE_FULL_ROW_LAYERS / SPARK_DSV41_FLASH_STAGE_PP_STAGES)
#define SPARK_DSV41_FLASH_STAGE_SIDEBAND_ROW_BYTES (4u * SPARK_DSV41_FLASH_STAGE_HIDDEN * 2u + (512u + 128u) * 2u + 4u)
#define SPARK_DSV41_FLASH_STAGE_VERIFY_ROWS 256u
#define SPARK_DSV41_FLASH_STAGE_HIDDEN 5120u
#define SPARK_DSV41_FLASH_STAGE_PAGE_TOKENS 256u
#define SPARK_DSV41_FLASH_STAGE_SLOT_BYTES 1280u
#define SPARK_DSV41_FLASH_STAGE_RATIO2_CACHES 3u
#define SPARK_DSV41_FLASH_STAGE_RATIO1_CACHES 1u
#define SPARK_DSV41_FLASH_STAGE_SHARD_GRAIN 8u
#define SPARK_DSV41_FLASH_STAGE_A2A_HEADS 8u
#define SPARK_DSV41_FLASH_STAGE_RECORD_FLOATS 514u
#define SPARK_DSV41_FLASH_STAGE_ENGRAM_SPLIT_ROWS 16u
#define SPARK_DSV41_FLASH_STAGE_MAX_POSITIONS 1048576u
#define SPARK_DSV41_FLASH_STAGE_LANDING_KEYS(positions, ratio) \
	((((positions) / (ratio) + SPARK_DSV41_FLASH_STAGE_SHARD_GRAIN * SPARK_DSV41_FLASH_STAGE_TP_DEGREE - 1u) / \
	(SPARK_DSV41_FLASH_STAGE_SHARD_GRAIN * SPARK_DSV41_FLASH_STAGE_TP_DEGREE)) * SPARK_DSV41_FLASH_STAGE_SHARD_GRAIN)
#define SPARK_DSV41_FLASH_STAGE_LANDING_ROWS(positions, ratio) \
	((SPARK_DSV41_FLASH_STAGE_LANDING_KEYS(positions, ratio) * SPARK_DSV41_FLASH_STAGE_SLOT_BYTES + 2u * SPARK_DSV41_FLASH_STAGE_HIDDEN - 1u) / \
	(2u * SPARK_DSV41_FLASH_STAGE_HIDDEN))

const SparkStageRunnerModelInterface *SparkDsv41FlashStageModel(void);

