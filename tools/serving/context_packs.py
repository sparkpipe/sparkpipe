class RequestError(Exception):
    def __init__(self, status, code, message, retry_after=None, details=None, overflow=None):
        super().__init__(message)
        self.status, self.code, self.message, self.retry_after, self.details, self.overflow = status, code, message, retry_after, details, overflow


def valid_name(value, kind):
    if not isinstance(value, str) or NAME.fullmatch(value) is None or ".." in value or value.endswith(".git"):
        raise RequestError(400, "invalid_name", f"a {kind} name is 1 to 64 letters, digits, '.', '-' or '_', starts with a letter or digit, "
                                                "has no '..' and does not end in .git")
    return value


def git_env(extra=None):
    environment = {key: value for key, value in os.environ.items() if not key.startswith("GIT_")}
    environment.update(GIT_ENVIRONMENT)
    environment.update(extra or {})
    return environment


def git(directory, *arguments, data=None, check=True):
    result = subprocess.run(["git", "-C", str(directory), *arguments], input=data, capture_output=True, env=git_env(), check=False)
    if result.returncode != 0:
        if not check:
            return None
        raise RequestError(409, "git_failed", f"git {arguments[0]}: " + result.stderr.decode("utf-8", "replace").strip()[:300])
    return result.stdout


def pattern_regex(pattern):
    directory = pattern.endswith("/")
    body = pattern.rstrip("/")
    out, index = [], 0
    while index < len(body):
        if body.startswith("**/", index):
            out.append("(?:.*/)?")
            index += 3
        elif body.startswith("**", index):
            out.append(".*")
            index += 2
        elif body[index] == "*":
            out.append("[^/]*")
            index += 1
        elif body[index] == "?":
            out.append("[^/]")
            index += 1
        else:
            out.append(re.escape(body[index]))
            index += 1
    text = "".join(out)
    anchored = "/" in body
    if directory:
        return re.compile(("" if anchored else "(?:.*/)?") + text + "/.*")
    return re.compile(("" if anchored else "(?:.*/)?") + text)


def matcher(patterns):
    compiled = [pattern_regex(pattern) for pattern in patterns]
    return lambda path: any(regex.fullmatch(path) for regex in compiled)


def patterns_valid(value, field, default):
    if value is None:
        return list(default)
    if not isinstance(value, list) or len(value) > MAX_PATTERNS or any(not isinstance(item, str) or not item or len(item) > PATTERN_LENGTH
                                                                       or item.startswith("/") for item in value):
        raise RequestError(400, "invalid_request", f"{field} is a list of at most {MAX_PATTERNS} relative path patterns (*, ** and ?)")
    return list(value)


def definition_valid(body, models, default_model, context_tokens):
    if not isinstance(body, dict):
        raise RequestError(400, "invalid_request", "a pack definition is a JSON object")
    unknown = sorted(set(body) - DEFINITION_FIELDS)
    if unknown:
        raise RequestError(400, "invalid_request", "unknown pack field: " + ", ".join(unknown))
    model = body.get("model", default_model)
    if model not in models:
        raise RequestError(400, "invalid_request", f"model must be one of {sorted(models)}")
    budget = body.get("budget_tokens")
    limit = context_tokens(model) - 1
    if isinstance(budget, bool) or not isinstance(budget, int) or not MIN_BUDGET_TOKENS <= budget <= limit:
        raise RequestError(400, "invalid_request", f"budget_tokens must be a whole number from {MIN_BUDGET_TOKENS} to {limit} for {model}")
    ref = body.get("ref", "HEAD")
    if not isinstance(ref, str) or not ref or len(ref) > 200 or ref.startswith("-") or any(char in ref for char in " ~^:?*[\\\0\n"):
        raise RequestError(400, "invalid_request", "ref names a branch, a tag or HEAD")
    return {"name": valid_name(body.get("name"), "pack"), "repo": valid_name(body.get("repo"), "repository"), "model": model,
            "include": patterns_valid(body.get("include"), "include", ["**"]), "exclude": patterns_valid(body.get("exclude"), "exclude", []),
            "budget_tokens": budget, "ref": ref}


def attribute(value):
    return value.replace("&", "&amp;").replace('"', "&quot;").replace("<", "&lt;").replace(">", "&gt;")


def render_header(definition):
    return (f'<pack name="{attribute(definition["name"])}" repository="{attribute(definition["repo"])}">\n'
            f'These files are a snapshot of the repository {definition["repo"]}, least-changed first. Each file is in a <file path commit> block, '
            "where commit is the last commit that changed it. The snapshot's own commit and its file count follow the last file. "
            "A file may have changed since the snapshot: read a file before you edit it.\n")


def render_file(path, commit, text):
    return f'<file path="{attribute(path)}" commit="{commit}">\n{text}{"" if not text or text.endswith(chr(10)) else chr(10)}</file>\n'


def render_footer(commit, files, left_out):
    return f'<snapshot commit="{commit}" files="{files}" left_out="{left_out}"/>\n</pack>\n'


def null_tokens(stream):
    buffer = b""
    while True:
        chunk = stream.read(STREAM_CHUNK)
        if not chunk:
            break
        buffer += chunk
        parts = buffer.split(b"\0")
        buffer = parts.pop()
        yield from parts
    if buffer:
        yield buffer


def history(directory, commit, paths):
    process = subprocess.Popen(["git", "-C", str(directory), "log", "--first-parent", "-m", "--no-renames", "--format=%x00%H%x00%ct", "--name-only", "-z", commit],
                               stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, env=git_env())
    wanted, changes, last = set(paths), {}, {}
    cutoff, inside, current, first = None, True, None, False
    tokens = null_tokens(process.stdout)
    try:
        for token in tokens:
            if not token:
                current = next(tokens, b"").decode()
                stamp = int(next(tokens, b"0") or 0)
                if cutoff is None:
                    cutoff = stamp - HISTORY_SECONDS
                if inside and stamp < cutoff:
                    inside = False
                if not inside and not wanted:
                    break
                first = True
                continue
            if first and token.startswith(b"\n"):
                token = token[1:]
            first = False
            path = token.decode("utf-8", "surrogateescape")
            if inside:
                changes[path] = changes.get(path, 0) + 1
            if path in wanted:
                wanted.discard(path)
                last[path] = current
                if not inside and not wanted:
                    break
    finally:
        process.kill()
        process.wait()
        process.stdout.close()
    return changes, last


def tree(directory, commit):
    entries = {}
    for entry in git(directory, "ls-tree", "-r", "-l", "-z", commit).split(b"\0"):
        if not entry:
            continue
        meta, raw = entry.split(b"\t", 1)
        mode, kind, blob, size = meta.split()
        if kind == b"blob" and mode != b"120000" and size != b"-":
            entries[raw.decode("utf-8", "surrogateescape")] = (blob.decode(), int(size))
    return entries


def read_blobs(directory, entries, paths):
    texts = {}
    for start in range(0, len(paths), READ_BATCH):
        part = paths[start:start + READ_BATCH]
        data = git(directory, "cat-file", "--batch", data="".join(entries[path][0] + "\n" for path in part).encode())
        offset = 0
        for path in part:
            end = data.index(b"\n", offset)
            size = int(data[offset:end].split()[2])
            texts[path] = data[end + 1:end + 1 + size]
            offset = end + 2 + size
    return texts


def resolve(directory, ref):
    found = git(directory, "rev-parse", "--verify", "--quiet", ref + "^{commit}", check=False)
    if not found:
        raise RequestError(409, "ref_not_found", f"the repository has no commit at {ref!r}; push it first")
    return found.decode().strip()


def build(directory, definition, model_id, encode, commit=None):
    commit = commit or resolve(directory, definition["ref"])
    entries = tree(directory, commit)
    include, exclude = matcher(definition["include"]), matcher(list(DEFAULT_EXCLUDE) + definition["exclude"])
    chosen = sorted(path for path in entries if include(path) and not exclude(path))
    changes, last = history(directory, commit, chosen)
    order = sorted(chosen, key=lambda path: (changes.get(path, 0), path))
    left_out = [{"path": path, "reason": "too_large"} for path in order if entries[path][1] > MAX_FILE_BYTES]
    readable = [path for path in order if entries[path][1] <= MAX_FILE_BYTES]
    texts = read_blobs(directory, entries, readable)
    ids = list(encode(render_header(definition)))
    header_tokens = len(ids)
    budget = definition["budget_tokens"] - FOOTER_RESERVE_TOKENS
    if header_tokens > budget:
        raise RequestError(400, "invalid_request", f"budget_tokens {definition['budget_tokens']} leaves no room for files after the pack header")
    files = []
    for path in readable:
        data = texts[path]
        if b"\0" in data[:BINARY_SCAN_BYTES]:
            left_out.append({"path": path, "reason": "binary"})
            continue
        try:
            text = data.decode("utf-8")
        except UnicodeDecodeError:
            left_out.append({"path": path, "reason": "binary"})
            continue
        if GENERATED.search(data[:GENERATED_SCAN_BYTES]):
            left_out.append({"path": path, "reason": "generated"})
            continue
        block = encode(render_file(path, last.get(path, commit), text))
        if len(ids) + len(block) > budget:
            left_out.append({"path": path, "reason": "over_budget", "tokens": len(block)})
            continue
        files.append({"path": path, "commit": last.get(path, commit), "changes": changes.get(path, 0), "offset": len(ids), "tokens": len(block)})
        ids.extend(block)
    footer_offset = len(ids)
    ids.extend(encode(render_footer(commit, len(files), len(left_out))))
    packed = array("I", ids)
    digest = hashlib.sha256(model_id.encode() + b"\0" + packed.tobytes()).hexdigest()
    left_out.sort(key=lambda entry: entry["path"])
    record = {"version": f"{definition['name']}@{digest[:DIGEST_CHARS]}", "pack": definition["name"], "repo": definition["repo"], "model": model_id,
              "commit": commit, "digest": digest, "tokens": len(ids), "header_tokens": header_tokens, "footer_offset": footer_offset,
              "files": files, "left_out": left_out, "definition": dict(definition)}
    return record, packed


def first_change(old, new):
    if old is None or old.get("header_tokens") != new["header_tokens"] or old.get("definition") != new["definition"]:
        return None, 0
    for before, after in zip(old["files"], new["files"]):
        if (before["path"], before["commit"], before["tokens"]) != (after["path"], after["commit"], after["tokens"]):
            return after["path"], after["offset"]
    if len(new["files"]) > len(old["files"]):
        entry = new["files"][len(old["files"])]
        return entry["path"], entry["offset"]
    return None, new["footer_offset"]


def resume_point(prefix_tokens, changed_at, resume_tokens):
    return (prefix_tokens + changed_at) // resume_tokens * resume_tokens


def splice(text, pieces, ids):
    marks = list(PACK_MARK.finditer(text))
    if len(marks) != 1:
        raise RequestError(400, "invalid_messages", "a message carries the pack marker, which only the fleet may write")
    mark = marks[0].group(0)
    result, done = [], False
    for piece, special in pieces:
        at = piece.find(mark) if not done and isinstance(special, bool) else -1
        if at < 0:
            result.append((piece, special))
            continue
        if at:
            result.append((piece[:at], special))
        result.append((mark, ids))
        if piece[at + len(mark):]:
            result.append((piece[at + len(mark):], special))
        done = True
    if not done:
        raise RequestError(400, "invalid_messages", "the chat template split the pack marker")
    return result


def pack_message(version):
    return {"role": "system", "content": f"SPARKPIPE-PACK {version}"}


def first_messages_key(messages):
    system = next((message.get("content") for message in messages if message.get("role") == "system"), None)
    user = next((message.get("content") for message in messages if message.get("role") == "user"), None)
    return "prefix:" + hashlib.sha256(json.dumps([system, user], sort_keys=True, ensure_ascii=False, default=str).encode()).hexdigest()[:32]


def write_json(path, value):
    temporary = path.with_name(path.name + ".writing")
    temporary.write_text(json.dumps(value, sort_keys=True))
    os.replace(temporary, path)


def directory_bytes(path):
    total = 0
    for folder, _, names in os.walk(path):
        for name in names:
            try:
                total += os.lstat(os.path.join(folder, name)).st_size
            except FileNotFoundError:
                pass
    return total


class Workspace:
    def __init__(self, root, max_push_bytes, max_repositories, max_packs):
        self.root = Path(root)
        self.max_push_bytes = max_push_bytes
        self.max_repositories = max_repositories
        self.max_packs = max_packs
        self.states = {}
        self.arrays = {}
        self.refreshes = {}
        self.root.mkdir(parents=True, exist_ok=True)
        self.root.chmod(0o700)

    def area(self, scope_dir):
        return self.root / scope_dir

    def touch(self, scope_dir, now=None):
        area = self.area(scope_dir)
        area.mkdir(mode=0o700, parents=True, exist_ok=True)
        stamp = area / LAST_USE
        stamp.touch()
        if now is not None:
            os.utime(stamp, (now, now))

    def last_use(self, scope_dir):
        area = self.area(scope_dir)
        for path in (area / LAST_USE, area):
            try:
                return os.lstat(path).st_mtime
            except FileNotFoundError:
                continue
        return None

    def repositories(self, scope_dir):
        return self.area(scope_dir) / "repos"

    def repository(self, scope_dir, name):
        path = self.repositories(scope_dir) / (valid_name(name, "repository") + ".git")
        return path if (path / "HEAD").is_file() else None

    def repository_names(self, scope_dir):
        folder = self.repositories(scope_dir)
        if not folder.is_dir():
            return []
        return sorted(path.name[:-4] for path in folder.iterdir() if path.name.endswith(".git") and (path / "HEAD").is_file())

    def create_repository(self, scope_dir, name):
        valid_name(name, "repository")
        if self.repository(scope_dir, name) is not None:
            raise RequestError(409, "repository_exists", f"there is already a repository {name!r}")
        if len(self.repository_names(scope_dir)) >= self.max_repositories:
            raise RequestError(409, "repository_limit", f"an account keeps at most {self.max_repositories} repositories on a fleet")
        self.touch(scope_dir)
        folder = self.repositories(scope_dir)
        folder.mkdir(parents=True, exist_ok=True)
        path = folder / (name + ".git")
        git(folder, "init", "--bare", "--quiet", "--initial-branch=main", path.name)
        for key, value in (("http.receivepack", "true"), ("http.uploadpack", "true"), ("receive.maxInputSize", str(self.max_push_bytes)),
                           ("core.hooksPath", os.devnull), ("gc.autoDetach", "false")):
            git(path, "config", key, value)
        self.touch(scope_dir)
        return self.describe_repository(scope_dir, name)

    def refs(self, path):
        found = git(path, "for-each-ref", "--format=%(refname)%00%(objectname)", check=False) or b""
        return dict(line.split("\0", 1) for line in found.decode("utf-8", "surrogateescape").splitlines() if "\0" in line)

    def settle_head(self, path):
        if git(path, "rev-parse", "--verify", "--quiet", "HEAD^{commit}", check=False):
            return
        branches = [ref for ref in self.refs(path) if ref.startswith("refs/heads/")]
        if len(branches) == 1:
            git(path, "symbolic-ref", "HEAD", branches[0])

    def describe_repository(self, scope_dir, name):
        path = self.repository(scope_dir, name)
        if path is None:
            raise RequestError(404, "repository_not_found", f"there is no repository {name!r}; create it with POST /v1/repos")
        head = git(path, "symbolic-ref", "--quiet", "HEAD", check=False)
        return {"name": name, "git": f"/git/{name}.git", "head": head.decode().strip() if head else None, "refs": self.refs(path),
                "bytes": directory_bytes(path), "packs": [pack for pack in self.pack_names(scope_dir) if self.definition(scope_dir, pack)["repo"] == name]}

    def delete_repository(self, scope_dir, name):
        path = self.repository(scope_dir, name)
        if path is None:
            raise RequestError(404, "repository_not_found", f"there is no repository {name!r}")
        shutil.rmtree(path)

    def packs(self, scope_dir):
        return self.area(scope_dir) / "packs"

    def pack_folder(self, scope_dir, name):
        return self.packs(scope_dir) / valid_name(name, "pack")

    def pack_names(self, scope_dir):
        folder = self.packs(scope_dir)
        if not folder.is_dir():
            return []
        return sorted(path.name for path in folder.iterdir() if (path / "definition.json").is_file())

    def definition(self, scope_dir, name):
        try:
            return json.loads((self.pack_folder(scope_dir, name) / "definition.json").read_text())
        except FileNotFoundError:
            return None

    def define(self, scope_dir, definition):
        if self.repository(scope_dir, definition["repo"]) is None:
            raise RequestError(404, "repository_not_found", f"there is no repository {definition['repo']!r}; create it with POST /v1/repos and push to it")
        existing = self.definition(scope_dir, definition["name"])
        if existing is None and len(self.pack_names(scope_dir)) >= self.max_packs:
            raise RequestError(409, "pack_limit", f"an account keeps at most {self.max_packs} packs on a fleet")
        folder = self.pack_folder(scope_dir, definition["name"])
        (folder / "versions").mkdir(parents=True, exist_ok=True)
        write_json(folder / "definition.json", definition)
        self.touch(scope_dir)

    def state(self, scope_dir, name):
        key = (scope_dir, name)
        if key not in self.states:
            try:
                self.states[key] = json.loads((self.pack_folder(scope_dir, name) / "state.json").read_text())
            except FileNotFoundError:
                self.states[key] = {"current": None, "versions": {}, "pins": {}, "profiles": []}
        return self.states[key]

    def save(self, scope_dir, name):
        folder = self.pack_folder(scope_dir, name)
        if folder.is_dir():
            write_json(folder / "state.json", self.state(scope_dir, name))

    def record(self, scope_dir, name, version):
        try:
            return json.loads((self.pack_folder(scope_dir, name) / "versions" / (version.partition("@")[2] + ".json")).read_text())
        except (FileNotFoundError, AttributeError):
            return None

    def ids(self, scope_dir, name, version):
        key = (scope_dir, name, version)
        if key not in self.arrays:
            values = array("I")
            values.frombytes((self.pack_folder(scope_dir, name) / "versions" / (version.partition("@")[2] + ".ids")).read_bytes())
            self.arrays[key] = values
        return self.arrays[key]

    def store(self, scope_dir, name, record, ids, now):
        if self.definition(scope_dir, name) is None:
            raise RequestError(409, "pack_deleted", f"pack {name!r} was deleted while it was being built")
        folder = self.pack_folder(scope_dir, name) / "versions"
        folder.mkdir(parents=True, exist_ok=True)
        stem = record["version"].partition("@")[2]
        temporary = folder / (stem + ".ids.writing")
        temporary.write_bytes(ids.tobytes())
        os.replace(temporary, folder / (stem + ".ids"))
        write_json(folder / (stem + ".json"), record)
        state = self.state(scope_dir, name)
        entry = state["versions"].setdefault(record["version"], {"commit": record["commit"], "tokens": record["tokens"], "built": now, "warm": None, "used": now})
        entry["used"] = max(entry.get("used") or 0, now)
        self.save(scope_dir, name)

    def mark_warm(self, scope_dir, name, version, warmed, now):
        state = self.state(scope_dir, name)
        entry = state["versions"][version]
        entry.update(warm=now, warmed=warmed)
        state["current"] = version
        self.drop_unused(scope_dir, name, now)
        self.save(scope_dir, name)

    def newest(self, state):
        built = [(entry["built"], version) for version, entry in state["versions"].items()]
        return max(built)[1] if built else None

    def pin(self, scope_dir, name, key, now):
        state = self.state(scope_dir, name)
        pinned = state["pins"].get(key)
        if pinned is not None and pinned["version"] in state["versions"]:
            pinned["used"] = now
            state["versions"][pinned["version"]]["used"] = now
            return pinned["version"]
        version = state["current"] or self.newest(state)
        if version is None:
            return None
        state["pins"][key] = {"version": version, "since": now, "used": now}
        state["versions"][version]["used"] = now
        self.save(scope_dir, name)
        return version

    def remember_profile(self, scope_dir, name, tools, kwargs):
        state = self.state(scope_dir, name)
        profile = {"tools": tools or None, "kwargs": kwargs or {}}
        if state["profiles"] and state["profiles"][0] == profile:
            return
        state["profiles"] = [profile] + [entry for entry in state["profiles"] if entry != profile][:MAX_PROFILES - 1]
        self.save(scope_dir, name)

    def drop_unused(self, scope_dir, name, now):
        state = self.state(scope_dir, name)
        dropped = []
        for version, entry in list(state["versions"].items()):
            if version != state["current"] and now - (entry.get("used") or entry["built"]) >= UNUSED_VERSION_SECONDS:
                dropped.append(version)
                del state["versions"][version]
                stem = version.partition("@")[2]
                for suffix in (".ids", ".json"):
                    (self.pack_folder(scope_dir, name) / "versions" / (stem + suffix)).unlink(missing_ok=True)
                self.arrays.pop((scope_dir, name, version), None)
        state["pins"] = {key: pin for key, pin in state["pins"].items() if pin["version"] in state["versions"] and now - pin["used"] < UNUSED_VERSION_SECONDS}
        return dropped

    def delete_pack(self, scope_dir, name):
        folder = self.pack_folder(scope_dir, name)
        if not (folder / "definition.json").is_file():
            raise RequestError(404, "pack_not_found", f"there is no pack {name!r}")
        shutil.rmtree(folder)
        self.forget(scope_dir, name)

    def forget(self, scope_dir, name=None):
        for key in [key for key in self.refreshes if key[0] == scope_dir and (name is None or key[1] == name)]:
            task = self.refreshes.pop(key).get("task")
            if task is not None:
                task.cancel()
        for key in [key for key in self.states if key[0] == scope_dir and (name is None or key[1] == name)]:
            del self.states[key]
        for key in [key for key in self.arrays if key[0] == scope_dir and (name is None or key[1] == name)]:
            del self.arrays[key]

    def delete_packs(self, scope_dir):
        folder = self.packs(scope_dir)
        found = folder.is_dir()
        if found:
            shutil.rmtree(folder)
        self.forget(scope_dir)
        return found

    def delete_area(self, scope_dir):
        area = self.area(scope_dir)
        found = area.is_dir()
        if found:
            shutil.rmtree(area)
        self.forget(scope_dir)
        return found

    def expire(self, rule):
        dropped = []
        if not self.root.is_dir():
            return dropped
        for area in sorted(self.root.iterdir()):
            if area.is_dir() and not area.is_symlink():
                used = self.last_use(area.name)
                if used is not None and rule(used):
                    self.delete_area(area.name)
                    dropped.append(area.name)
        return dropped

    def describe_pack(self, scope_dir, name):
        definition = self.definition(scope_dir, name)
        if definition is None:
            raise RequestError(404, "pack_not_found", f"there is no pack {name!r}; build one with POST /v1/packs")
        state = self.state(scope_dir, name)
        current = self.record(scope_dir, name, state["current"]) if state["current"] else None
        refresh = self.refreshes.get((scope_dir, name))
        return {"name": name, "definition": definition, "alias": f"{definition['model']}+{name}", "current": state["current"],
                "state": "warm" if state["current"] else ("building" if refresh else "empty"),
                "refreshing": bool(refresh), "versions": state["versions"],
                "files": [{key: entry[key] for key in ("path", "commit", "tokens")} for entry in current["files"]] if current else [],
                "left_out": current["left_out"] if current else [], "sessions": len(state["pins"]),
                "last_refresh": state.get("last_refresh")}


async def git_backend(request, project_root, name, tail, user, max_bytes):
    service = request.query.get("service")
    environment = git_env({"GIT_PROJECT_ROOT": str(project_root), "GIT_HTTP_EXPORT_ALL": "1", "PATH_INFO": f"/{name}.git/{tail}",
                           "REQUEST_METHOD": request.method, "QUERY_STRING": request.query_string, "REMOTE_USER": user, "REMOTE_ADDR": "127.0.0.1",
                           "CONTENT_TYPE": request.headers.get("Content-Type", ""), "GIT_HTTP_MAX_REQUEST_BUFFER": str(max_bytes)})
    protocol = request.headers.get("Git-Protocol")
    if protocol and re.fullmatch(r"[A-Za-z0-9=:._-]{1,64}", protocol):
        environment["HTTP_GIT_PROTOCOL"] = protocol
    process = await asyncio.create_subprocess_exec("git", "http-backend", stdin=asyncio.subprocess.PIPE, stdout=asyncio.subprocess.PIPE,
                                                   stderr=asyncio.subprocess.PIPE, env=environment)
    received = 0

    async def feed():
        nonlocal received
        try:
            if request.method == "POST":
                async for chunk in request.content.iter_chunked(STREAM_CHUNK):
                    received += len(chunk)
                    if received > max_bytes:
                        raise OverflowError
                    process.stdin.write(chunk)
                    await process.stdin.drain()
        finally:
            try:
                process.stdin.close()
            except (BrokenPipeError, ConnectionResetError):
                pass

    feeding = asyncio.ensure_future(feed())
    errors = asyncio.ensure_future(process.stderr.read())
    try:
        head = b""
        while b"\r\n\r\n" not in head and b"\n\n" not in head:
            chunk = await process.stdout.read(STREAM_CHUNK)
            if not chunk:
                break
            head += chunk
        try:
            await feeding
        except OverflowError:
            raise RequestError(413, "push_too_large", f"a push carries at most {max_bytes} bytes on this fleet") from None
        except (BrokenPipeError, ConnectionResetError):
            pass
        split = head.find(b"\r\n\r\n")
        cut = (split, split + 4) if split >= 0 else (head.find(b"\n\n"), head.find(b"\n\n") + 2)
        if cut[0] < 0:
            await process.wait()
            raise RequestError(502, "git_failed", "git http-backend gave no reply: " + (await errors).decode("utf-8", "replace").strip()[:300])
        status, headers = 200, {}
        for line in head[:cut[0]].decode("latin-1").splitlines():
            field, _, value = line.partition(":")
            if field.strip().lower() == "status":
                status = int(value.strip().split()[0])
            elif field.strip():
                headers[field.strip()] = value.strip()
        response = web.StreamResponse(status=status, headers=headers)
        await response.prepare(request)
        body = head[cut[1]:]
        if body:
            await response.write(body)
        while True:
            chunk = await process.stdout.read(STREAM_CHUNK)
            if not chunk:
                break
            await response.write(chunk)
        await response.write_eof()
        code = await process.wait()
        await errors
        return response, status, code, service, received
    finally:
        if not feeding.done():
            feeding.cancel()
        if process.returncode is None:
            process.kill()
            await process.wait()
        if not errors.done():
            errors.cancel()
