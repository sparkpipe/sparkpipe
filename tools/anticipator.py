def resolve_c(path, include, snapshot, by_name):
    local = posixpath.normpath(posixpath.join(posixpath.dirname(path), include))
    if local in snapshot.files:
        return local
    top = path.split("/", 1)[0]
    matches = [item for item in by_name.get(posixpath.basename(include), ()) if item == include or item.endswith("/" + include)]
    if not matches:
        return None
    return sorted(matches, key=lambda item: (item.split("/", 1)[0] != top, len(item), item))[0]


def resolve_python(path, module, snapshot):
    dots = len(module) - len(module.lstrip("."))
    rest = module.lstrip(".").replace(".", "/")
    directory = posixpath.dirname(path)
    bases = []
    if dots:
        base = directory
        for _ in range(dots - 1):
            base = posixpath.dirname(base)
        bases.append(base)
    else:
        base = directory
        while True:
            bases.append(base)
            if not base:
                break
            base = posixpath.dirname(base)
    for base in bases:
        stem = posixpath.join(base, rest) if rest else base
        for candidate in (stem + ".py", posixpath.join(stem, "__init__.py")):
            candidate = posixpath.normpath(candidate)
            if candidate in snapshot.files:
                return candidate
    return None


def resolve_relative(path, target, snapshot, endings):
    joined = posixpath.normpath(posixpath.join(posixpath.dirname(path), target))
    if joined.startswith(".."):
        return None
    for ending in endings:
        if joined + ending in snapshot.files:
            return joined + ending
    return None


def dependencies(path, data, snapshot, by_name):
    found = set()
    if path.endswith(C_SUFFIXES):
        for match in C_INCLUDE.finditer(data):
            found.add(resolve_c(path, match.group(1).decode("utf-8", "replace"), snapshot, by_name))
    elif path.endswith(".py"):
        for match in PY_FROM.finditer(data):
            module = match.group(1).decode()
            found.add(resolve_python(path, module, snapshot))
            for name in match.group(2).decode().replace("(", " ").split(","):
                name = name.strip().split(" ")[0]
                if name and name != "*":
                    found.add(resolve_python(path, module.rstrip(".") + "." + name if module.strip(".") else module + name, snapshot))
        for match in PY_IMPORT.finditer(data):
            for name in match.group(1).decode().split(","):
                name = name.strip().split(" ")[0]
                if name:
                    found.add(resolve_python(path, name, snapshot))
    elif path.endswith(SCRIPT_SUFFIXES):
        for match in JS_IMPORT.finditer(data):
            found.add(resolve_relative(path, match.group(1).decode(), snapshot, ("", ".js", ".mjs", ".ts", ".tsx", ".jsx", "/index.js", "/index.ts")))
    elif path.endswith(MARKUP_SUFFIXES):
        for match in HTML_LINK.finditer(data):
            found.add(resolve_relative(path, match.group(1).decode(), snapshot, ("",)))
    found.discard(None)
    found.discard(path)
    return found


def structure(snapshot, plannable):
    by_name = {}
    for path in snapshot.files:
        by_name.setdefault(posixpath.basename(path), []).append(path)
    sources = [path for path in plannable if path.endswith(C_SUFFIXES + (".py",) + SCRIPT_SUFFIXES + MARKUP_SUFFIXES)
               and snapshot.files[path][1] <= MAX_SOURCE_BYTES]
    snapshot.read(sources)
    deps = {}
    for path in sorted(sources):
        found = sorted(item for item in dependencies(path, snapshot.texts[path], snapshot, by_name) if item in plannable)
        if found:
            deps[path] = found
    dependents = {}
    for path, targets in deps.items():
        for target in targets:
            dependents.setdefault(target, []).append(path)
    names = [(path, posixpath.basename(path).lower()) for path in sorted(plannable) if "test" in path.lower()]
    tests = {}
    for path in sorted(plannable):
        stem = posixpath.splitext(posixpath.basename(path))[0].lower()
        if len(stem) >= 4 and "test" not in path.lower():
            found = [item for item, name in names if stem in name]
            if 0 < len(found) <= MAX_TESTS_PER_FILE:
                tests[path] = found
    return {"deps": deps, "dependents": dependents, "tests": tests}


def history(snapshot, now):
    since, until = int(now - HISTORY_DAYS * DAY), int(now)
    raw = git(snapshot.repo, "log", "--no-merges", "--format=%x1e%H %ct", "--name-only", f"--since=@{since}", f"--until=@{until}", snapshot.commit)
    commits = []
    for chunk in raw.decode("utf-8", "surrogateescape").split("\x1e"):
        lines = [line for line in chunk.split("\n") if line]
        if not lines:
            continue
        sha, stamp = lines[0].split()
        commits.append((int(stamp), sha, sorted(set(line for line in lines[1:] if line in snapshot.files))))
    commits.sort()
    changes, heat, pairs, today, touched = {}, {}, {}, set(), {}
    for stamp, sha, files in commits:
        weight = 0.5 ** (max(0.0, now - stamp) / DAY / HISTORY_HALF_LIFE)
        for path in files:
            changes[path] = changes.get(path, 0) + 1
            heat[path] = heat.get(path, 0.0) + weight
            touched.setdefault(path, set()).add(sha)
        if now - stamp <= DAY:
            today.update(files)
        if 2 <= len(files) <= MAX_COMMIT_FILES:
            share = 1.0 / (len(files) - 1)
            for index, first in enumerate(files):
                for second in files[index + 1:]:
                    pairs[(first, second)] = pairs.get((first, second), 0.0) + share
    return {"changes": changes, "heat": heat, "pairs": pairs, "today": today, "touched": touched, "commits": len(commits)}


def branches(snapshot, now):
    raw = git(snapshot.repo, "for-each-ref", "--format=%(objectname) %(committerdate:unix) %(refname)", "refs/heads", "refs/remotes")
    rows, seen = [], set()
    for line in sorted(raw.decode().splitlines()):
        parts = line.split(" ", 2)
        if len(parts) != 3 or not parts[1].isdigit():
            continue
        sha, stamp, ref = parts[0], int(parts[1]), parts[2]
        if sha != snapshot.commit and now - BRANCH_DAYS * DAY <= stamp <= now:
            rows.append((-stamp, ref, sha))
    heat = {}
    for negative, ref, sha in sorted(rows):
        if sha in seen or len(seen) >= BRANCH_LIMIT:
            continue
        seen.add(sha)
        base = git(snapshot.repo, "merge-base", snapshot.commit, sha, check=False)
        if base is None or base.decode().strip() == sha:
            continue
        changed = git(snapshot.repo, "diff", "--name-only", base.decode().strip(), sha, check=False) or b""
        weight = 0.5 ** ((now + negative) / DAY / SESSION_HALF_LIFE)
        for path in changed.decode("utf-8", "surrogateescape").splitlines():
            if path in snapshot.files:
                heat[path] = max(heat.get(path, 0.0), weight)
    return {"heat": heat, "refs": len(seen)}


def sessions(records, plannable, now):
    per = {}
    for record in records:
        stamp = to_epoch(record.get("time"))
        path, kind, session = record.get("path"), record.get("kind"), record.get("session")
        if stamp is None or stamp > now or now - stamp > SESSION_DAYS * DAY or path not in plannable or kind not in KIND_WEIGHT or not session:
            continue
        entry = per.setdefault(session, {"time": stamp, "files": {}, "counts": {}})
        entry["time"] = max(entry["time"], stamp)
        entry["files"][path] = max(entry["files"].get(path, 0.0), KIND_WEIGHT[kind])
        entry["counts"][path] = entry["counts"].get(path, 0.0) + KIND_WEIGHT[kind]
    heat, pairs = {}, {}
    for session in sorted(per):
        entry = per[session]
        entry["weight"] = 0.5 ** ((now - entry["time"]) / DAY / SESSION_HALF_LIFE)
        for path, weight in entry["files"].items():
            heat[path] = heat.get(path, 0.0) + entry["weight"] * weight
        files = sorted(entry["files"], key=lambda item: (-entry["files"][item], item))[:MAX_SESSION_FILES]
        files.sort()
        for index, first in enumerate(files):
            for second in files[index + 1:]:
                pairs[(first, second)] = pairs.get((first, second), 0) + 1
    return {"per": per, "heat": heat, "pairs": pairs}


def keywords(text):
    return set(word for word in WORDS.findall(text.lower()) if word not in STOP_WORDS)


def words_match(word, part):
    return min(len(word), len(part)) >= 4 and (word.startswith(part) or part.startswith(word))


def hint_heat(hints, plannable):
    heat = {}
    for pattern in hints["paths"]:
        prefix = pattern.rstrip("/") + "/"
        for path in plannable:
            if fnmatch.fnmatchcase(path, pattern) or path.startswith(prefix):
                heat[path] = 1.0
    phrases = [keywords(item) for item in hints["phrases"] + hints["tasks"]]
    phrases = [item for item in phrases if item]
    if phrases:
        for path in plannable:
            parts = set(WORDS.findall(path.lower()))
            for words in phrases:
                share = sum(1 for word in words if any(words_match(word, part) for part in parts)) / len(words)
                if share >= 0.5:
                    heat[path] = max(heat.get(path, 0.0), share)
    return heat


