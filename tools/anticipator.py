def number(value):
    return isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(value)


def clock_minutes(text, field):
    match = CLOCK.fullmatch(text) if isinstance(text, str) else None
    if match is None:
        raise Refused(f"{field} must be HH:MM")
    return int(match.group(1)) * 60 + int(match.group(2))


def window_hours(window):
    span = (clock_minutes(window.get("end"), "window.end") - clock_minutes(window.get("start"), "window.start")) % 1440
    return (span or 1440) / 60.0


