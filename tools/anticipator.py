def profile_for(models, model):
    if model not in models:
        raise Refused(f"model has no profile: {model}")
    profile = models[model]
    for field in ("prefill_tokens_per_s", "resume_tokens", "cache_bytes_per_token_node", "cache_bytes_node", "window_tokens"):
        if not number(profile.get(field)) or profile[field] <= 0:
            raise Refused(f"{model}: {field} is not measured yet")
    return {key: profile[key] for key in ("prefill_tokens_per_s", "resume_tokens", "cache_bytes_per_token_node", "cache_bytes_node", "window_tokens")}


def settings_valid(raw, models, base=None):
    if not isinstance(raw, dict):
        raise Refused("settings must be an object")
    unknown = sorted(set(raw) - set(DEFAULT_SETTINGS))
    if unknown:
        raise Refused("unknown setting: " + ", ".join(unknown))
    merged = json.loads(json.dumps(base or DEFAULT_SETTINGS))
    for key, value in raw.items():
        if key in ("window", "signals"):
            if not isinstance(value, dict):
                raise Refused(f"{key} must be an object")
            extra = sorted(set(value) - set(DEFAULT_SETTINGS[key]))
            if extra:
                raise Refused(f"unknown {key} field: " + ", ".join(extra))
            merged[key].update(value)
        else:
            merged[key] = value
    if merged["mode"] not in MODES:
        raise Refused("mode must be off, plan or auto")
    hours = window_hours(merged["window"])
    try:
        ZoneInfo(str(merged["window"].get("zone")))
    except (ZoneInfoNotFoundError, ValueError):
        raise Refused("window.zone must be an IANA time zone") from None
    if merged["max_hours"] is not None and (not number(merged["max_hours"]) or not 0 < merged["max_hours"] <= hours):
        raise Refused(f"max_hours must be above 0 and at most the window's {hours:g} hours")
    if not number(merged["cache_share"]) or not 0 < merged["cache_share"] <= 1:
        raise Refused("cache_share must be above 0 and at most 1")
    if any(not isinstance(merged["signals"].get(name), bool) for name in SIGNALS):
        raise Refused("signals must set structure, history, sessions and hints to true or false")
    if not isinstance(merged["exclude"], list) or any(not isinstance(item, str) or not item for item in merged["exclude"]):
        raise Refused("exclude must be a list of path patterns")
    if merged["model"] is not None and merged["model"] not in models:
        raise Refused(f"model has no profile: {merged['model']}")
    limit = models[merged["model"]]["window_tokens"] if merged["model"] else max(item["window_tokens"] for item in models.values())
    if "max_leaf_tokens" not in raw and number(merged["max_leaf_tokens"]) and merged["max_leaf_tokens"] > limit:
        merged["max_leaf_tokens"] = limit
    tokens = merged["max_leaf_tokens"]
    if not isinstance(tokens, int) or isinstance(tokens, bool) or not 1 <= tokens <= limit:
        raise Refused(f"max_leaf_tokens must be a whole number from 1 to {limit}")
    return merged


def hints_valid(raw):
    if raw is None:
        return {"date": None, "paths": [], "phrases": [], "tasks": [], "pins": []}
    if not isinstance(raw, dict):
        raise Refused("focus must be an object")
    unknown = sorted(set(raw) - set(HINT_FIELDS))
    if unknown:
        raise Refused("unknown focus field: " + ", ".join(unknown))
    date = raw.get("date")
    if date is not None and (not isinstance(date, str) or not DATE.fullmatch(date)):
        raise Refused("focus date must be YYYY-MM-DD")
    hints = {"date": date}
    for field in ("paths", "phrases", "tasks", "pins"):
        value = raw.get(field, [])
        if not isinstance(value, list) or any(not isinstance(item, str) or not item.strip() for item in value):
            raise Refused(f"focus {field} must be a list of strings")
        hints[field] = sorted(set(item.strip() for item in value))
    return hints


def excluded(path, patterns):
    name = posixpath.basename(path)
    for pattern in patterns:
        if pattern.endswith("/"):
            if path.startswith(pattern) or ("/" + pattern) in ("/" + path):
                return True
        elif fnmatch.fnmatchcase(path, pattern) or fnmatch.fnmatchcase(name, pattern):
            return True
    return False


def git(repo, *args, data=None, check=True):
    result = subprocess.run(["git", "-C", str(repo), *args], input=data, capture_output=True, check=False)
    if result.returncode != 0:
        if not check:
            return None
        raise Refused(f"git {args[0]}: " + result.stderr.decode("utf-8", "replace").strip()[:300])
    return result.stdout


def to_epoch(value):
    if number(value):
        return float(value)
    if isinstance(value, str) and value:
        try:
            moment = datetime.fromisoformat(value.replace("Z", "+00:00"))
        except ValueError:
            return None
        if moment.tzinfo is None:
            moment = moment.replace(tzinfo=timezone.utc)
        return moment.timestamp()
    return None


def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":")).encode()).hexdigest()


def padded(tokens, boundary):
    return 0 if tokens <= 0 else int(math.ceil(tokens / boundary) * boundary)


class Snapshot:
    def __init__(self, repo, commit="HEAD"):
        self.repo = Path(repo).resolve()
        self.commit = git(self.repo, "rev-parse", "--verify", commit + "^{commit}").decode().strip()
        self.files = {}
        for entry in git(self.repo, "ls-tree", "-r", "-l", "-z", self.commit).split(b"\0"):
            if not entry:
                continue
            meta, raw = entry.split(b"\t", 1)
            mode, kind, blob, size = meta.split()
            if kind == b"blob" and mode != b"120000" and size != b"-":
                self.files[raw.decode("utf-8", "surrogateescape")] = (blob.decode(), int(size))
        self.texts = {}
        common = git(self.repo, "rev-parse", "--path-format=absolute", "--git-common-dir", check=False)
        self.common = common.decode().strip() if common else None
        ignored = git(self.repo, "ls-files", "-z", "-c", "-i", "--exclude-standard", check=False) or b""
        self.ignored = set(item.decode("utf-8", "surrogateescape") for item in ignored.split(b"\0") if item)

    def read(self, paths):
        wanted = sorted(path for path in set(paths) if path in self.files and path not in self.texts)
        for start in range(0, len(wanted), 2000):
            part = wanted[start:start + 2000]
            data = git(self.repo, "cat-file", "--batch", data="".join(self.files[path][0] + "\n" for path in part).encode())
            offset = 0
            for path in part:
                end = data.index(b"\n", offset)
                size = int(data[offset:end].split()[2])
                self.texts[path] = data[end + 1:end + 1 + size]
                offset = end + 2 + size

    def same_repository(self, directory):
        if not directory:
            return False
        if directory == str(self.repo) or directory.startswith(str(self.repo) + "/"):
            return True
        if self.common is None or not os.path.isdir(directory):
            return False
        other = git(directory, "rev-parse", "--path-format=absolute", "--git-common-dir", check=False)
        return other is not None and other.decode().strip() == self.common


class Tokens:
    def __init__(self, tokenizer=None, pattern=None):
        self.known = {}
        self.encoder = None
        self.kind = "estimate"
        if tokenizer and str(tokenizer).endswith(".model"):
            import tiktoken
            from tiktoken.load import load_tiktoken_bpe
            if not pattern:
                raise Refused("a tiktoken tokenizer needs the model profile's tiktoken_pattern")
            encoding = tiktoken.Encoding(name="anticipator", pat_str="|".join(pattern), mergeable_ranks=load_tiktoken_bpe(str(tokenizer)), special_tokens={})
            self.encoder = lambda texts: [len(item) for item in encoding.encode_ordinary_batch(texts)]
        elif tokenizer:
            from tokenizers import Tokenizer
            loaded = Tokenizer.from_file(str(tokenizer))
            self.encoder = lambda texts: [len(item.ids) for item in loaded.encode_batch(texts, add_special_tokens=False)]
        if tokenizer:
            self.kind = "tokenizer:" + hashlib.sha256(Path(tokenizer).read_bytes()).hexdigest()[:16]

    def count(self, items):
        todo = [(key, text) for key, text in items if key not in self.known]
        for start in range(0, len(todo), TOKEN_BATCH):
            part = todo[start:start + TOKEN_BATCH]
            if self.encoder is not None:
                counts = self.encoder([text for _, text in part])
            else:
                counts = [int(math.ceil(len(text.encode("utf-8")) / ESTIMATE_BYTES_PER_TOKEN)) for _, text in part]
            for (key, _), count in zip(part, counts):
                self.known[key] = count
        return {key: self.known[key] for key, _ in items}


