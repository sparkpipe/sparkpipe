#!/usr/bin/env python3
import json
import os
import subprocess
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import anticipator as A

NOW = datetime(2026, 11, 5, 19, 0, tzinfo=timezone.utc).timestamp()
DAY = 86400
MODELS = {"test-model": {"prefill_tokens_per_s": 50, "resume_tokens": 64, "cache_bytes_per_token_node": 1000,
                         "cache_bytes_node": 1_000_000_000, "window_tokens": 200000},
          "unmeasured": {"prefill_tokens_per_s": 50, "resume_tokens": 64, "cache_bytes_per_token_node": None,
                         "cache_bytes_node": 1_000_000_000, "window_tokens": 200000}}
FILES = {
    "AGENTS.md": "Read a file before you edit it.\n",
    "README.md": "A small test repository.\n",
    "include/common.h": "#pragma once\nint common(void);\n",
    "src/net/net.h": '#include "common.h"\nint net_open(void);\n',
    "src/net/crypto.c": '#include "net.h"\n#include "common.h"\nint crypto(void) { return net_open(); }\n' + "/* body */\n" * 60,
    "src/net/socket.c": '#include "net.h"\nint socket_open(void) { return 1; }\n' + "/* body */\n" * 60,
    "src/alloc/alloc.h": '#include "common.h"\nvoid *allocate(int);\n',
    "src/alloc/alloc.c": '#include "alloc.h"\nvoid *allocate(int n) { return 0; }\n' + "/* body */\n" * 60,
    "src/alloc/arena.c": '#include "alloc.h"\nint arena(void) { return 2; }\n' + "/* body */\n" * 60,
    "tests/test_crypto.py": "import sys\n" + "x = 1\n" * 30,
    "docs/notes.md": "Notes.\n",
    ".env": "SECRET=1\n",
    "keys/server.pem": "-----BEGIN-----\n",
    "vendor/lib.c": "int vendored(void) { return 0; }\n",
    "src/gen/table.c": "// @generated by a tool\nint table[] = {1};\n",
    "src/private/secret.c": "int hidden(void) { return 3; }\n",
}


def git(repo, *args, when=None):
    env = dict(os.environ, GIT_AUTHOR_NAME="t", GIT_AUTHOR_EMAIL="t@example.com", GIT_COMMITTER_NAME="t", GIT_COMMITTER_EMAIL="t@example.com")
    if when is not None:
        stamp = f"@{int(when)} +0000"
        env.update(GIT_AUTHOR_DATE=stamp, GIT_COMMITTER_DATE=stamp)
    subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True, env=env)


def write(repo, path, text):
    target = repo / path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text)


def make_repo(base):
    repo = base / "repo"
    repo.mkdir()
    git(repo, "init", "-q", "-b", "main")
    for path, text in FILES.items():
        write(repo, path, text)
    (repo / "src/net/logo.bin").write_bytes(b"\0\1\2" * 100)
    git(repo, "add", "-A")
    git(repo, "commit", "-q", "-m", "start", when=NOW - 60 * DAY)
    for days, paths in ((20, ["src/alloc/alloc.c", "src/alloc/arena.c"]), (3, ["src/net/crypto.c", "src/net/socket.c"]),
                        (0.5, ["src/net/crypto.c", "tests/test_crypto.py"])):
        for path in paths:
            write(repo, path, (repo / path).read_text() + f"/* change {days} */\n")
        git(repo, "add", "-A")
        git(repo, "commit", "-q", "-m", f"change {days}", when=NOW - days * DAY)
    return repo


def records(session, days, paths, kind="read"):
    when = datetime.fromtimestamp(NOW - days * DAY, timezone.utc).isoformat().replace("+00:00", "Z")
    return [{"session": session, "time": when, "kind": kind, "path": path} for path in paths]


EVIDENCE = (records("s1", 0.2, ["src/net/crypto.c", "src/net/net.h", "src/net/socket.c"], "edit")
            + records("s2", 0.4, ["src/net/crypto.c", "src/net/net.h"])
            + records("s3", 1.2, ["src/net/socket.c", "src/net/crypto.c"])
            + records("s4", 5.5, ["src/alloc/alloc.c", "src/alloc/arena.c"])
            + records("s5", 0.3, [".env", "vendor/lib.c", "src/net/crypto.c"]))
SETTINGS = {"model": "test-model", "max_leaf_tokens": 20000, "window": {"start": "19:00", "end": "09:00", "zone": "UTC"}}


def run(repo, settings=None, hints=None, records_in=EVIDENCE, previous=None, unused=None):
    return A.plan(repo, dict(SETTINGS, **(settings or {})), MODELS, NOW, records=records_in, hints=hints, previous=previous, unused=unused)


def files_of(plan):
    found = set(item["path"] for item in plan["root"]["files"])
    for trunk in plan["trunks"].values():
        found |= set(item["path"] for item in trunk["files"])
    for leaf in plan["leaves"]:
        found |= set(item["path"] for item in leaf["files"])
    return found


def leaf_names(plan):
    return [leaf["name"] for leaf in plan["leaves"]]


def check(condition, message, failures):
    if not condition:
        failures.append(message)


def main():
    failures = []
    with tempfile.TemporaryDirectory() as temporary:
        base = Path(temporary)
        repo = make_repo(base)
        first = run(repo)
        second = run(repo)
        check(json.dumps({k: v for k, v in first.items() if k != "seconds"}, sort_keys=True)
              == json.dumps({k: v for k, v in second.items() if k != "seconds"}, sort_keys=True), "same inputs give the same plan", failures)
        names = leaf_names(first)
        check("core/src-net" in names, f"the hot module becomes a leaf: {names}", failures)
        net = next((leaf for leaf in first["leaves"] if leaf["name"] == "core/src-net"), None)
        if net:
            check(any(item["signal"] == "sessions" for item in net["signals"]), "the net leaf names its session evidence", failures)
            check(any(item["signal"] == "history" for item in net["signals"]), "the net leaf names its history", failures)
            check(net["reasons"] and net["expected_uses"] > 0 and net["build_seconds"] > 0, "every leaf has reasons, uses and build time", failures)
            check(net["pack_tokens"] <= SETTINGS["max_leaf_tokens"], "a leaf pack stays within max_leaf_tokens", failures)
        for level in [first["root"]] + list(first["trunks"].values()) + first["leaves"]:
            check(level["padded_tokens"] % 64 == 0 and level["padded_tokens"] >= level["tokens"], "every level ends on the resume boundary", failures)
        check(first["totals"]["build_seconds"] <= first["budgets"]["compute_seconds"], "the plan stays within the compute budget", failures)
        check(first["totals"]["cache_bytes_node"] <= first["budgets"]["cache_bytes_node"], "the plan stays within the cache budget", failures)
        check("AGENTS.md" in set(item["path"] for item in first["root"]["files"]), "project instructions go in the root", failures)

        excluded = {".env", "keys/server.pem", "vendor/lib.c", "src/gen/table.c", "src/net/logo.bin", "src/private/secret.c"}
        hinted = run(repo, settings={"exclude": ["src/private/"]}, hints={"paths": ["src/**"]},
                     records_in=EVIDENCE + records("s6", 0.1, ["src/private/secret.c", "src/gen/table.c", "src/net/logo.bin"], "edit"))
        for plan_doc in (first, hinted):
            check(not (files_of(plan_doc) & excluded), f"excluded paths never enter a pack: {sorted(files_of(plan_doc) & excluded)}", failures)

        tight = run(repo, settings={"max_hours": 0.001})
        check(tight["totals"]["build_seconds"] <= 3.6 and len(tight["leaves"]) <= len(first["leaves"]), "a small compute budget plans less", failures)
        check(any("compute" in item["reason"] for item in tight["skipped"]) or len(tight["leaves"]) < len(first["leaves"]) or not first["leaves"],
              "a leaf left out for compute says so", failures)
        small = run(repo, settings={"cache_share": 0.0000001})
        check(small["totals"]["cache_bytes_node"] <= small["budgets"]["cache_bytes_node"] and not small["leaves"], "a small cache budget plans nothing", failures)

        quiet = run(repo, settings={"signals": {"sessions": False}})
        check(all(item["signal"] != "sessions" for leaf in quiet["leaves"] for item in leaf["signals"]), "a switched-off signal is never used", failures)
        check(quiet["evidence"]["sessions"] == 0, "sessions off reads no session evidence", failures)
        only_hints = run(repo, settings={"signals": {"sessions": False, "history": False, "structure": False}}, hints={"paths": ["src/alloc/**"]})
        check(leaf_names(only_hints) == ["core/src-alloc"], f"with only hints, the hinted module is planned: {leaf_names(only_hints)}", failures)

        before = run(repo, settings={"max_hours": 0.2})
        after = run(repo, settings={"max_hours": 0.2}, hints={"phrases": ["allocator arena"]})
        check("core/src-alloc" in leaf_names(after) and leaf_names(before) != leaf_names(after), "focus hints change the next plan", failures)

        try:
            A.plan(repo, dict(SETTINGS, model="unmeasured"), MODELS, NOW)
            failures.append("a model without measured cache bytes is refused")
        except A.Refused as error:
            check("not measured" in str(error), "the refusal names the unmeasured figure", failures)

        off = run(repo, settings={"mode": "off"})
        check(off["leaves"] == [] and A.build_list(off, A.settings_valid({"mode": "off"}, MODELS)) == [], "mode off builds nothing", failures)

        store = A.Store(base / "store", MODELS)
        status, value = A.api(store, "PUT", "/v1/anticipator", body={"cache_share": 2})
        check(status == 400 and "cache_share" in value["message"], "an invalid setting is refused", failures)
        status, value = A.api(store, "PUT", "/v1/anticipator", body={"colour": "red"})
        check(status == 400, "an unknown setting is refused", failures)
        status, value = A.api(store, "PUT", "/v1/anticipator", body={"mode": "plan", "model": "test-model", "max_leaf_tokens": 20000})
        check(status == 200 and value["mode"] == "plan", "settings are stored", failures)
        planned = A.plan(repo, store.settings(), MODELS, NOW, records=EVIDENCE)
        store.save_plan(planned)
        check(store.build_list() == [], "plan mode builds nothing until approved", failures)
        status, value = A.api(store, "POST", "/v1/anticipator/plan/approve", body={"leaves": ["core/nothing"]})
        check(status == 400, "approving a leaf outside the plan is refused", failures)
        if planned["leaves"]:
            chosen = planned["leaves"][0]["name"]
            status, value = A.api(store, "POST", "/v1/anticipator/plan/approve", body={"leaves": [chosen]})
            check(status == 200 and store.build_list() == [chosen], "only approved leaves are built", failures)
        status, value = A.api(store, "GET", "/v1/anticipator/plan")
        check(status == 200 and value["approval_required"], "the plan says approval is required", failures)
        A.api(store, "PUT", "/v1/anticipator", body={"mode": "auto"})
        status, value = A.api(store, "POST", "/v1/anticipator/plan/approve", body={"leaves": "all"})
        check(status == 409, "approval outside plan mode is a conflict", failures)
        check(store.build_list() == leaf_names(planned), "auto mode builds the whole plan", failures)
        status, value = A.api(store, "PUT", "/v1/anticipator/focus", body={"paths": ["src/alloc/**"], "phrases": ["allocator migration"]})
        check(status == 200 and store.focus()["paths"] == ["src/alloc/**"], "focus hints are stored", failures)
        status, value = A.api(store, "PUT", "/v1/anticipator/focus", body={"paths": "src"})
        check(status == 400, "malformed focus is refused", failures)
        check(A.api(store, "GET", "/v1/anticipator/report")[0] == 404, "no report before one is made", failures)

        built = leaf_names(planned)
        day_start = NOW + 5 * 3600
        telemetry = []
        if built:
            telemetry = [
                {"request": "r1", "session": "a", "pack": f"test-model+{built[0]}@abc", "time": day_start + 100, "prompt_tokens": 1000, "cached_tokens": 900, "cold_prefill_ms_estimate": 18000},
                {"request": "r2", "session": "a", "pack": f"test-model+{built[0]}@abc", "time": day_start + 200, "prompt_tokens": 1500, "cached_tokens": 1400, "cold_prefill_ms_estimate": 28000},
                {"request": "r3", "session": "b", "pack": None, "time": day_start + 300, "prompt_tokens": 800, "cached_tokens": 0, "cold_prefill_ms_estimate": None},
                {"request": "r4", "session": "c", "pack": f"{built[0]}@abc", "time": day_start + 400, "prompt_tokens": 2000, "cached_tokens": 1000, "cold_prefill_ms_estimate": 20000},
                {"request": "r0", "session": "z", "pack": f"{built[0]}@abc", "time": day_start - 9 * 3600, "prompt_tokens": 5, "cached_tokens": 5, "cold_prefill_ms_estimate": 99},
            ]
        result = A.report(planned, built[:1] + ["core/never"], telemetry, day_start, day_start + DAY, {"unused_nights": {"core/never": 2}})
        if built:
            check(result["sessions_started"] == 3 and result["sessions_on_anticipated_leaf"] == 2, "sessions and their starts reconcile", failures)
            check(result["first_turn_prompt_tokens"] == 3000 and result["first_turn_cached_tokens"] == 1900, "first-turn tokens reconcile", failures)
            check(result["prefill_avoided_ms"] == 66000, "prefill avoided sums the telemetry", failures)
            check(result["records"] == 4, "records outside the day are left out", failures)
        check([item["name"] for item in result["unused"]] == ["core/never"] and result["unused_nights"]["core/never"] == 3, "unused leaves are counted", failures)
        if built:
            penalised = run(repo, unused={built[0]: 4})
            normal = next(leaf for leaf in first["leaves"] if leaf["name"] == built[0]) if built[0] in leaf_names(first) else None
            again = next((leaf for leaf in penalised["leaves"] if leaf["name"] == built[0]), None)
            check(normal is None or again is None or again["expected_uses"] < normal["expected_uses"], "a leaf unused for three nights loses score", failures)

        refreshed = run(repo, previous=first)
        if first["leaves"] and refreshed["leaves"]:
            check(refreshed["totals"]["build_seconds"] < first["totals"]["build_seconds"], "an unchanged warm leaf is not rebuilt", failures)

        claude = base / "claude"
        claude.mkdir()
        lines = [
            {"type": "assistant", "sessionId": "cc1", "timestamp": "2026-11-05T10:00:00Z", "cwd": str(repo),
             "message": {"content": [{"type": "tool_use", "name": "Read", "input": {"file_path": str(repo / "src/net/crypto.c")}},
                                     {"type": "tool_use", "name": "Edit", "input": {"file_path": str(repo / "src/net/net.h"), "old_string": "SECRET", "new_string": "x"}},
                                     {"type": "tool_use", "name": "Bash", "input": {"command": "sed -n 1,20p src/alloc/alloc.c && git show main:docs/notes.md"}},
                                     {"type": "tool_use", "name": "Read", "input": {"file_path": "/etc/passwd"}}]}},
            {"type": "assistant", "sessionId": "cc2", "timestamp": "2026-11-05T10:00:00Z", "cwd": str(base),
             "message": {"content": [{"type": "tool_use", "name": "Read", "input": {"file_path": str(base / "README.md")}}]}},
        ]
        (claude / "s.jsonl").write_text("\n".join(json.dumps(line) for line in lines) + "\n")
        codex = base / "codex"
        codex.mkdir()
        codex_lines = [
            {"timestamp": "2026-11-05T11:00:00Z", "type": "session_meta", "payload": {"id": "cx1", "cwd": str(repo)}},
            {"timestamp": "2026-11-05T11:00:01Z", "type": "response_item", "payload": {"type": "custom_tool_call", "name": "apply_patch",
                                                                                         "input": "*** Begin Patch\n*** Update File: src/alloc/arena.c\n@@\n*** End Patch"}},
            {"timestamp": "2026-11-05T11:00:02Z", "type": "response_item", "payload": {"type": "function_call", "name": "shell",
                                                                                         "arguments": json.dumps({"command": ["bash", "-lc", "cat src/net/socket.c"]})}},
        ]
        (codex / "rollout.jsonl").write_text("\n".join(json.dumps(line) for line in codex_lines) + "\n")
        found = A.evidence(A.Snapshot(repo), NOW, [claude], [codex])
        pairs = sorted((item["kind"], item["path"]) for item in found)
        check(("read", "src/net/crypto.c") in pairs and ("edit", "src/net/net.h") in pairs, "Claude Code reads and edits become evidence", failures)
        check(("read", "src/alloc/alloc.c") in pairs and ("read", "docs/notes.md") in pairs, "paths in shell commands become evidence", failures)
        check(("edit", "src/alloc/arena.c") in pairs and ("read", "src/net/socket.c") in pairs, "Codex patches and shell reads become evidence", failures)
        check(all(item["path"] in A.Snapshot(repo).files for item in found), "only repository paths are kept", failures)
        check(not any("SECRET" in json.dumps(item) or "cc1" in json.dumps(item) for item in found), "evidence keeps no content and no raw session id", failures)
        check(not any(item["path"] == "README.md" for item in found), "a session in another directory is not this repository's", failures)

        output = base / "plan.json"
        (base / "models.json").write_text(json.dumps({"models": MODELS}))
        (base / "settings.json").write_text(json.dumps(SETTINGS))
        code = A.main(["--models", str(base / "models.json"), "plan", "--repo", str(repo), "--now", str(NOW), "--out", str(output),
                       "--settings", str(base / "settings.json")])
        check(code == 0 and json.loads(output.read_text())["format"] == A.PLAN_FORMAT, "the command line writes a plan", failures)

    for failure in failures:
        print(f"FAIL: {failure}")
    print(f"{'FAIL' if failures else 'PASS'} test_anticipator ({len(failures)} failures)")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
