DAY = 86400
PUSH_LIMIT = 256 << 10
RESUME = 128
BUDGET = 6000
PUBLIC = "http.extraHeader=X-SparkPipe-Public: 1"
CLIENT = {"GIT_CONFIG_NOSYSTEM": "1", "GIT_CONFIG_GLOBAL": os.devnull, "GIT_TERMINAL_PROMPT": "0", "GIT_AUTHOR_NAME": "Dev",
          "GIT_AUTHOR_EMAIL": "dev@example.com", "GIT_COMMITTER_NAME": "Dev", "GIT_COMMITTER_EMAIL": "dev@example.com"}
