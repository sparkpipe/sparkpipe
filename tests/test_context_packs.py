REPOSITORIES = {"repositories":{"directory": "workspace", "max_push_bytes": PUSH_LIMIT, "max_repositories": 2, "max_packs": 2}}


def client_env(when=None):
    environment = {key: value for key, value in os.environ.items() if not key.startswith("GIT_")}
    environment.update(CLIENT)
    if when is not None:
        environment.update(GIT_AUTHOR_DATE=f"@{int(when)} +0000", GIT_COMMITTER_DATE=f"@{int(when)} +0000")
    return environment


def run(directory, *arguments, when=None, check=True):
    result = subprocess.run(["git", "-C", str(directory), "-c", "credential.helper=", *arguments], capture_output=True, env=client_env(when))
    if check and result.returncode != 0:
        raise AssertionError(f"git {' '.join(arguments)}: {result.stderr.decode()}")
    return result


def commit(work, files, message, when):
    for name, data in files.items():
        path = work / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data if isinstance(data, bytes) else data.encode())
    run(work, "add", "-A")
    run(work, "commit", "-q", "-m", message, when=when)
    return run(work, "rev-parse", "HEAD").stdout.decode().strip()


def source(name, version):
    return "".join(f"def {name}_{index}(value):\n    return value + {index * version}\n\n" for index in range(6))


def common_prefix(left, right):
    size = 0
    for a, b in zip(left, right):
        if a != b:
            break
        size += 1
    return size


async def until(condition, seconds=30):
    deadline = time.monotonic() + seconds
    while time.monotonic() < deadline:
        if condition():
            return True
        await asyncio.sleep(0.05)
    return False


async def call(harness, method, path, body=None, **headers):
    async with harness.session.request(method, harness.base + path, json=body, headers=harness.headers(**headers)) as response:
        text = await response.text()
        return response.status, response.headers, json.loads(text) if text else None


async def ask(harness, messages, session=None, tools=True, model="alpha+core", **headers):
    body = {"model": model, "messages": messages}
    if tools:
        body["tools"] = TOOLS
    if session:
        headers["X-Claude-Code-Session-Id"] = session
    async with harness.session.post(harness.base + "/v1/chat/completions", json=body, headers=harness.headers(**headers)) as response:
        text = await response.text()
        data = json.loads(text)
        return response.status, response.headers, data


def git_url(harness, key):
    return harness.base.replace("http://", f"http://dev:{key}@") + "/git/main.git"


async def push(harness, work, key, *extra, branch="main"):
    return await asyncio.to_thread(run, work, "-c", PUBLIC, *extra, "push", git_url(harness, key), branch, check=False)


def history(work, base):
    shas = {}
    shas["o1"] = commit(work, {"README.md": "# Service\n\nRead AGENTS.md first.\n", "src/core.py": source("core", 1)}, "old one", base - 200 * DAY)
    shas["o2"] = commit(work, {"README.md": "# Service\n\nRead AGENTS.md first. Tests live in tests/.\n"}, "old two", base - 199 * DAY)
    shas["o3"] = commit(work, {"README.md": "# Service\n\nRead AGENTS.md first. Tests live in tests/ and run with make.\n"}, "old three", base - 198 * DAY)
    shas["c1"] = commit(work, {"docs/guide.md": "# Guide\n\nStart the service with make run.\n", "src/hot.py": source("hot", 1), "src/util.py": source("util", 1),
                               "assets/logo.png": b"\x89PNG\r\n\x1a\n\0\0\0\rIHDR" + bytes(range(256)) * 4,
                               "gen/out.py": "# Code generated by protoc. DO NOT EDIT.\nVALUE = 1\n", "gen/api_pb2.py": "VALUE = 2\n",
                               "big.txt": "".join(f"line {index} of a large log that does not fit the pack budget\n" for index in range(900))},
                        "recent one", base - 4 * DAY)
    shas["c2"] = commit(work, {"src/hot.py": source("hot", 2)}, "recent two", base - 3 * DAY)
    shas["c3"] = commit(work, {"src/hot.py": source("hot", 3), "docs/guide.md": "# Guide\n\nStart the service with make run, then open the dashboard.\n"},
                        "recent three", base - 2 * DAY)
    shas["c4"] = commit(work, {"src/hot.py": source("hot", 4)}, "recent four", base - DAY)
    return shas


async def repository_rules(harness, work, check):
    status, _, body = await call(harness, "POST", "/v1/repos", {"name": "../main"})
    check(status == 400 and body["error"]["code"] == "invalid_name", f"a repository name cannot climb out of the account's directory: {status} {body}")
    result = await push(harness, work, harness.key)
    check(result.returncode != 0, "a push to a repository that was never created fails")
    status, _, body = await call(harness, "POST", "/v1/repos", {"name": "main"})
    check(status == 201 and body["git"] == "/git/main.git" and body["refs"] == {}, f"POST /v1/repos creates an empty bare repository: {status} {body}")
    status, _, body = await call(harness, "POST", "/v1/repos", {"name": "main"})
    check(status == 409 and body["error"]["code"] == "repository_exists", f"creating the same repository twice is refused: {status} {body}")

    async with harness.session.get(harness.base + "/git/main.git/info/refs?service=git-receive-pack", headers={fixture.HEADER: "1"}) as response:
        check(response.status == 401 and response.headers.get("WWW-Authenticate") == 'Basic realm="SparkPipe"',
              f"git without a key gets 401 with a Basic challenge, so git asks for credentials: {response.status} {dict(response.headers)}")
    result = await push(harness, work, "sk-sp-" + "0" * 40)
    check(result.returncode != 0, "a push with a wrong key fails")
    result = await push(harness, work, harness.key)
    head = run(work, "rev-parse", "HEAD").stdout.decode().strip()
    scope_dir = harness.frontend.scope_directory("key:" + harness.key_id)
    bare = harness.frontend.workspace.repository(scope_dir, "main")
    check(result.returncode == 0 and bare is not None and harness.frontend.workspace.refs(bare).get("refs/heads/main") == head,
          f"git push over smart HTTP with the SparkPipe key as the Basic password updates the fleet's bare copy: {result.stderr.decode()[-300:]}")
    check(bare is not None and str(bare).startswith(str(harness.tmp / "workspace")) and os.stat(bare.parent.parent).st_mode & 0o777 == 0o700
          and os.stat(harness.tmp / "workspace").st_mode & 0o777 == 0o700,
          "the bare copy lives under the configured repositories directory, in an area only the serving user can open")
    fetched = await asyncio.to_thread(run, work, "-c", PUBLIC, "ls-remote", git_url(harness, harness.key), check=False)
    check(fetched.returncode == 0 and head in fetched.stdout.decode(), "the same key fetches from its repository")

    gateway = ["-c", "http.extraHeader=X-SparkPipe-Account: acme"]
    fetched = await asyncio.to_thread(run, work, "-c", PUBLIC, *gateway, "ls-remote", harness.base.replace("http://", f"http://dev:{harness.gateway_key}@") + "/git/main.git",
                                      check=False)
    check(fetched.returncode != 0 and head not in fetched.stdout.decode(), "another account, through the gateway, cannot read the repository")
    status, _, body = await call(harness, "GET", "/v1/repos", account="acme")
    check(status == 200 and body["data"] == [], f"another account lists none of the first account's repositories: {body}")
    status, _, body = await call(harness, "GET", "/v1/repos/main", swap=True)
    check(status == 404 and body["error"]["code"] == "repository_not_found", f"another key's account does not see the repository: {status} {body}")
    result = await asyncio.to_thread(run, work, "-c", PUBLIC, "push", git_url(harness, harness.swap_key), "main", check=False)
    check(result.returncode != 0, "another key cannot push to the repository")

    run(work, "checkout", "-q", "-b", "blob")
    commit(work, {"blob.bin": random.Random(7).randbytes(PUSH_LIMIT + (64 << 10))}, "too large", time.time())
    sized = await push(harness, work, harness.key, branch="blob")
    chunked = await push(harness, work, harness.key, "-c", "http.postBuffer=4096", branch="blob")
    check(sized.returncode != 0 and chunked.returncode != 0 and all("HTTP 413" in result.stderr.decode() for result in (sized, chunked))
          and "refs/heads/blob" not in harness.frontend.workspace.refs(bare),
          "pushes over max_push_bytes are refused, with a Content-Length and as a chunked body, and leave the copy unchanged")
    run(work, "checkout", "-q", "main")
    return scope_dir, bare


async def pack_rules(harness, work, shas, scope_dir, bare, check):
    engine, frontend = harness.engine, harness.frontend
    frontend.models["alpha"].resume_tokens = RESUME
    status, _, body = await call(harness, "POST", "/v1/packs", {"name": "core", "repo": "main", "budget_tokens": 100})
    check(status == 400, f"a budget below the minimum is refused: {status}")
    status, _, body = await call(harness, "POST", "/v1/packs", {"name": "core", "repo": "main", "budget_tokens": BUDGET, "secret": 1})
    check(status == 400, "an unknown pack field is refused")
    status, _, body = await call(harness, "POST", "/v1/packs", {"name": "core", "repo": "main", "budget_tokens": BUDGET})
    check(status == 202 and body["definition"]["model"] == "alpha" and body["alias"] == "alpha+core",
          f"POST /v1/packs defines a pack for the first resident model and starts building it: {status} {body}")
    check(await until(lambda: frontend.workspace.state(scope_dir, "core")["current"] is not None), "the first version is built and warmed in the background")
    status, _, pack = await call(harness, "GET", "/v1/packs/core")
    v1 = pack["current"]
    warm = engine.requests[-1]
    check(warm["max_tokens"] == 1 and warm["priority"] == chat_frontend.BACKGROUND_PRIORITY,
          f"the warm-up asks the engine for one token at background priority: {warm['max_tokens']} {warm['priority']}")
    check([entry["path"] for entry in pack["files"]] == ["README.md", "src/core.py", "src/util.py", "docs/guide.md", "src/hot.py"],
          f"files are ordered least-changed in the 90 days before the commit, ties by path, so old README edits count for nothing: {[entry['path'] for entry in pack['files']]}")
    check(sorted((entry["path"], entry["reason"]) for entry in pack["left_out"]) == [("assets/logo.png", "binary"), ("big.txt", "over_budget"), ("gen/out.py", "generated")],
          f"binary, generated and over-budget files are left out and listed; default-excluded generated stubs are not packed: {pack['left_out']}")
    check({entry["path"]: entry["commit"] for entry in pack["files"]} == {"README.md": shas["o3"], "src/core.py": shas["o1"], "src/util.py": shas["c1"],
                                                                          "docs/guide.md": shas["c3"], "src/hot.py": shas["c4"]},
          "each file block names the last commit that changed that file")

    definition = frontend.workspace.definition(scope_dir, "core")
    model = frontend.models["alpha"]
    encode = lambda text: model.vocabulary.encode(text, False)
    copy = harness.tmp / "copy.git"
    run(harness.tmp, "clone", "-q", "--bare", str(bare), str(copy))
    first, first_ids = context_packs.build(bare, definition, "alpha", encode)
    again, again_ids = context_packs.build(bare, definition, "alpha", encode)
    other, other_ids = context_packs.build(copy, definition, "alpha", encode, commit=shas["c4"])
    stored = frontend.workspace.ids(scope_dir, "core", v1)
    check(list(first_ids) == list(again_ids) == list(other_ids) == list(stored) and first["version"] == again["version"] == other["version"] == v1,
          "the same commit gives the same tokens every time, from the fleet's copy or another clone")
    expected = context_packs.render_header(definition)
    for entry in first["files"]:
        expected += context_packs.render_file(entry["path"], entry["commit"], run(work, "show", f"{shas['c4']}:{entry['path']}").stdout.decode())
    expected += context_packs.render_footer(shas["c4"], len(first["files"]), len(first["left_out"]))
    check(harness.tokenizer.decode(list(first_ids), skip_special_tokens=False) == expected and len(first_ids) <= BUDGET,
          "the tokens are the model tokenizer's encoding of a fixed header, one <file path commit> block per file and a footer naming the commit, within budget")
    check(expected.index("<file") > 0 and f'commit="{shas["c4"]}"' not in expected[:expected.index("</file>")],
          "the pack commit appears only after the last file, so the stable files stay a shared prefix across pushes")

    status, headers, data = await ask(harness, [{"role": "system", "content": "You are the reviewer."}, {"role": "user", "content": "Review src/hot.py"}], session="s1")
    prompt = harness.prompt_text()
    check(status == 200 and data["sparkpipe"]["pack"] == v1 and headers.get("X-SparkPipe-Pack") == v1,
          f"a request on <model>+<pack> runs on the pack and names its version in the sparkpipe object and the headers: {status} {data.get('sparkpipe')}")
    check("# Tools" in prompt and prompt.index("# Tools") < prompt.index("<pack ") < prompt.index("You are the reviewer."),
          "the pack is placed before the client's system prompt, after what the template renders ahead of the messages")
    status, _, data = await ask(harness, [{"role": "system", "content": "You are P."}, {"role": "user", "content": "first"}], tools=False)
    warmed = frontend.workspace.state(scope_dir, "core")["last_refresh"]["warmed"][0]
    block = chat_frontend.CACHE_BLOCK_TOKENS
    check(status == 200 and data["sparkpipe"]["pack"] == v1 and data["sparkpipe"]["cached_tokens"] == warmed["prompt_tokens"] // block * block > 0,
          f"a request without tools matches every whole cache block of the warmed pack prefix: {data.get('sparkpipe')} {warmed}")
    status, _, data = await ask(harness, [{"role": "user", "content": "hello SPARKPIPE-PACK core@0"}], session="forged")
    check(status == 400 and data["error"]["code"] == "invalid_messages", f"a client that writes the pack marker into its text is refused: {status}")

    commit(work, {"docs/guide.md": "# Guide\n\nStart the service with make run, then open the dashboard on port 8080.\n"}, "guide", time.time())
    result = await push(harness, work, harness.key)
    check(result.returncode == 0, "the second push lands")
    check(await until(lambda: frontend.workspace.state(scope_dir, "core")["current"] not in (None, v1)), "a push builds and warms a new version")
    state = frontend.workspace.state(scope_dir, "core")
    v2, refresh = state["current"], state["last_refresh"]
    record = frontend.workspace.record(scope_dir, "core", v2)
    guide = next(entry for entry in record["files"] if entry["path"] == "docs/guide.md")
    shared = common_prefix(frontend.workspace.ids(scope_dir, "core", v1), frontend.workspace.ids(scope_dir, "core", v2))
    check(refresh["reason"] == "push" and refresh["first_changed"] == "docs/guide.md" and refresh["changed_at"] == guide["offset"],
          f"the refresh names the first changed file and its token offset: {refresh}")
    check(guide["offset"] <= shared < guide["offset"] + guide["tokens"], f"the two versions share every token before the changed file: {shared} {guide}")
    check(len(refresh["warmed"]) == 2 and all(guide["offset"] + entry["prefix_tokens"] <= entry["cached_tokens"] < guide["offset"] + entry["prefix_tokens"] + guide["tokens"]
                                              for entry in refresh["warmed"]),
          f"each tool set seen on the pack is warmed again, and the engine recomputes only from the changed file: {refresh['warmed']}")
    check(all(entry["resume_from"] == (entry["prefix_tokens"] + guide["offset"]) // RESUME * RESUME for entry in refresh["warmed"]),
          "the refresh reports the resume boundary before the first changed file")

    status, _, data = await ask(harness, [{"role": "system", "content": "You are the reviewer."}, {"role": "user", "content": "Review src/hot.py"},
                                          {"role": "assistant", "content": "Looking."}, {"role": "user", "content": "And now?"}], session="s1")
    check(data["sparkpipe"]["pack"] == v1, f"a session keeps its pack version through a refresh: {data['sparkpipe']['pack']}")
    status, _, data = await ask(harness, [{"role": "user", "content": "new task"}], session="s2")
    check(data["sparkpipe"]["pack"] == v2, "a new session gets the new warm version")
    status, _, data = await ask(harness, [{"role": "system", "content": "You are P."}, {"role": "user", "content": "first"}, {"role": "assistant", "content": "ok"},
                                          {"role": "user", "content": "second"}], tools=False)
    check(data["sparkpipe"]["pack"] == v1, "a conversation without a session id keeps its version by its first system and user messages")
    status, _, data = await ask(harness, [{"role": "system", "content": "You are P."}, {"role": "user", "content": "other"}], tools=False)
    check(data["sparkpipe"]["pack"] == v2, "another conversation without a session id gets the new version")

    gate = asyncio.Event()
    original = frontend.warm_prefix

    async def held(model, ids, scope):
        await gate.wait()
        return await original(model, ids, scope)

    frontend.warm_prefix = held
    commit(work, {"src/hot.py": source("hot", 5)}, "hot five", time.time())
    result = await push(harness, work, harness.key)
    check(await until(lambda: len(frontend.workspace.state(scope_dir, "core")["versions"]) == 3), "the third version is built")
    status, _, data = await ask(harness, [{"role": "user", "content": "while warming"}], session="s3")
    check(data["sparkpipe"]["pack"] == v2 and frontend.workspace.state(scope_dir, "core")["current"] == v2,
          f"while the new version warms, new sessions get the last warm version: {data['sparkpipe']['pack']}")
    gate.set()
    check(await until(lambda: frontend.workspace.state(scope_dir, "core")["current"] not in (v1, v2)), "the alias moves once the new version is warm")
    frontend.warm_prefix = original
    v3 = frontend.workspace.state(scope_dir, "core")["current"]
    pins = [(await ask(harness, [{"role": "user", "content": "ping"}], session=session))[2]["sparkpipe"]["pack"] for session in ("s1", "s2", "s3", "s4")]
    check(pins == [v1, v2, v2, v3], f"each session stays on the version it started on, and new sessions start on the newest warm one: {pins}")

    async with harness.session.post(harness.base + "/v1/messages", json={"model": "alpha+core", "max_tokens": 32, "system": "Claude system prompt.",
                                                                         "messages": [{"role": "user", "content": "hi"}]},
                                    headers=harness.headers(**{"X-Claude-Code-Session-Id": "s5"})) as response:
        data = json.loads(await response.text())
    prompt = harness.prompt_text()
    check(response.status == 200 and data["sparkpipe"]["pack"] == v3 and prompt.index("<pack ") < prompt.index("Claude system prompt."),
          f"Messages requests take the pack ahead of their system prompt too: {response.status} {data.get('sparkpipe')}")

    status, _, data = await call(harness, "GET", "/v1/models")
    check({"id": "alpha+core", "pack": "core", "model": "alpha", "version": v3, "state": "warm"} in data["packs"], f"/v1/models lists the pack: {data['packs']}")
    status, _, data = await call(harness, "GET", "/v1/models", account="acme")
    check(data["packs"] == [], "another account's model list shows no packs")
    status, _, data = await ask(harness, [{"role": "user", "content": "hi"}], account="acme")
    check(status == 404 and data["error"]["code"] == "pack_not_found", "another account cannot use the pack")
    status, _, data = await ask(harness, [{"role": "user", "content": "hi"}], model="beta+core", swap=True)
    check(status == 404 and data["error"]["code"] == "pack_not_found", "a pack serves only the model it was tokenized for")

    dropped = frontend.workspace.drop_unused(scope_dir, "core", time.time() + 2 * DAY)
    check(sorted(dropped) == sorted([v1, v2]) and frontend.workspace.state(scope_dir, "core")["current"] == v3
          and not (frontend.workspace.pack_folder(scope_dir, "core") / "versions" / (v1.partition("@")[2] + ".ids")).exists(),
          f"versions no session used for 24 hours are dropped, the current one is kept: {dropped}")


async def deletion_rules(harness, scope_dir, check):
    frontend = harness.frontend
    status, _, body = await call(harness, "DELETE", "/v1/cache")
    check(status == 200 and "packs" in body["deleted"] and "repositories" not in body["deleted"], f"DELETE /v1/cache deletes the packs: {body}")
    status, _, body = await call(harness, "GET", "/v1/packs")
    _, _, repos = await call(harness, "GET", "/v1/repos")
    check(body["data"] == [] and [entry["name"] for entry in repos["data"]] == ["main"], "the packs are gone and the repository stays")
    status, _, body = await call(harness, "DELETE", "/v1/cache?storage=true")
    check(status == 200 and "repositories" in body["deleted"] and not frontend.workspace.area(scope_dir).exists(),
          f"DELETE /v1/cache?storage=true deletes the repositories too: {body}")

    status, _, body = await call(harness, "POST", "/v1/repos", {"name": "side"}, account="acme")
    acme = frontend.workspace.area(frontend.scope_directory("account:acme"))
    check(status == 201 and acme.is_dir(), "a gateway account creates its own repository")
    now = time.time()
    harness.directive(now + 5, now + 5)
    frontend.expire_working_state(now + 10, False)
    _, _, repos = await call(harness, "GET", "/v1/repos", account="acme")
    check(not acme.exists() and repos["data"] == [], "a change of user deletes the earlier account's repositories and packs with its working state")


async def run_all(tmp, check):
    work = tmp / "work"
    work.mkdir()
    run(work, "init", "-q", "--initial-branch=main")
    shas = history(work, int(time.time()))
    async with fixture.Harness(tmp, extra=REPOSITORIES) as harness:
        scope_dir, bare = await repository_rules(harness, work, check)
        await pack_rules(harness, work, shas, scope_dir, bare, check)
        await deletion_rules(harness, scope_dir, check)


def main():
    check = fixture.Checks("test_context_packs")
    captured = io.StringIO()
    with tempfile.TemporaryDirectory() as directory, contextlib.redirect_stderr(captured):
        asyncio.run(run_all(Path(directory), check))
    if check.failures:
        print(captured.getvalue()[-4000:])
    check.finish("git push over smart HTTP with the SparkPipe key updates the account's bare copy, other accounts and keys see nothing, and pushes over "
                 "max_push_bytes are refused; a pack is ordered least-changed first and the same commit always gives the same tokens; a push warms the "
                 "new version in the background and only the tokens after the first changed file are recomputed; sessions keep their version through a "
                 "refresh, new sessions get a version only once it is warm, and the sparkpipe object names it; unused versions, DELETE /v1/cache and a "
                 "change of user delete packs and repositories")


if __name__ == "__main__":
    main()
